import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileSnapshot } from './b06-harness.mjs';
const reportPath = 'docs/reports/B06-acceptance-browser-files.json';
const run = JSON.parse(await fs.readFile('docs/reports/B06-acceptance-browser-runtime.json', 'utf8'));
const get = async route => { const r = await fetch(run.api + route); assert.equal(r.status,200); return r.json(); };
const wiki = await get('/api/wiki/' + run.wikiId);
const list = await get('/api/audits?wikiId=' + run.wikiId);
const details = await Promise.all(list.items.map(a => get('/api/audits/' + a.id)));
const rawFiles = await fileSnapshot(path.join(run.dataRoot,'knowledge/raw'));
const wikiFiles = await fileSnapshot(path.join(run.dataRoot,'knowledge/wiki'));
assert.deepEqual(rawFiles, run.beforeRaw);
const snapshot = { phase:process.argv[2], wiki, details, rawFiles, wikiFiles, stats:await get('/api/stats') };
const previous = await fs.readFile(reportPath,'utf8').then(JSON.parse,()=>[]);
if (process.argv[2] === 'preview') {
  assert.deepEqual(wikiFiles,run.beforeWiki);
  assert.equal(details.length,1);
  assert.equal(details[0].draft.id,'9460a3c9-d45a-4e87-b925-1a72dcb57702');
  assert.equal(details[0].draft.revision,2);
  assert.equal(details[0].draft.replacement,'铺货率采用有销售门店数除以目标门店数（浏览器人工确认）');
} else if (process.argv[2] === 'final') {
  assert.equal(wiki.revision,3);
  assert.ok(wiki.body.includes('## 人工保留\n不要删除这条人工备注。'));
  assert.ok(wiki.body.includes('铺货率采用有销售门店数除以目标门店数（浏览器人工确认）。'));
  assert.ok(wiki.body.includes('浏览器整页确认补充。'));
  assert.deepEqual(wiki.aliases,['浏览器原别名']);
  assert.deepEqual(wiki.sources,[run.rawId]);
  for (const decision of ['accepted','partial','rejected','deferred']) assert.ok(details.some(d=>d.audit.decisionHistory.some(h=>h.decision===decision)),decision);
  assert.equal(details.filter(d=>d.audit.status==='open').length,1);
  assert.equal(snapshot.stats.openAuditCount,1);
} else if (process.argv[2] === 'post-ui-repair') {
  assert.equal(wiki.revision,3);
  const successful = previous.find(p=>p.phase==='final');
  assert.ok(successful);
  assert.equal(wikiFiles[run.wikiId+'.md'],successful.wikiFiles[run.wikiId+'.md']);
  const allAudits = await get('/api/audits');
  assert.equal(snapshot.stats.openAuditCount,allAudits.items.filter(a=>a.status==='open').length);
  snapshot.allAudits=allAudits;
  const origin=allAudits.items.find(a=>a.comment==='UI延迟建议A：原页保存，不污染其他选择。');
  const late=allAudits.items.find(a=>a.comment==='UI延迟建议B：同页切换应保留当前A草稿。');
  assert.ok(origin&&late); assert.equal(origin.wikiId,late.wikiId);
  const originWiki=await get('/api/wiki/'+origin.wikiId);
  assert.equal(origin.status,'resolved'); assert.equal(late.status,'open');
  assert.equal(originWiki.revision,3);
  assert.equal(originWiki.body,'铺货率采用有销售门店数除以目标门店数。\nUI返修后人工保存确认。');
  snapshot.raceDetails=[await get('/api/audits/'+origin.id),await get('/api/audits/'+late.id)];
  snapshot.raceWiki=originWiki;
} else throw Error('phase required');
previous.push(snapshot); await fs.writeFile(reportPath,JSON.stringify(previous,null,2));
console.log(JSON.stringify({phase:snapshot.phase,revision:wiki.revision,audits:details.length,rawUnchanged:true,openAudits:snapshot.stats.openAuditCount}));
