import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const session=JSON.parse(await readFile(process.argv[2],'utf8'));
const out=path.resolve(process.argv[3] ?? 'docs/reports/RAWURL01-20261106-evidence');
await mkdir(out,{recursive:true});
const {chromium}=createRequire(import.meta.url)(path.join(os.homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const browser=await chromium.launch({executablePath:path.join(os.homedir(),'AppData/Local/Google/Chrome/Application/chrome.exe'),args:['--no-proxy-server'],headless:true});
const page=await browser.newPage({viewport:{width:1536,height:1050}});
page.setDefaultTimeout(15000);
const evidence={success:false,checks:[],screenshots:[],pageErrors:[],externalBrowserRequests:[],extractions:[]};
page.on('pageerror',e=>evidence.pageErrors.push(e.message));
page.on('request',request=>{
  const url=new URL(request.url());
  if(['http:','https:'].includes(url.protocol)&&url.origin!==session.url)evidence.externalBrowserRequests.push(url.origin);
  if(request.method()==='POST'&&url.pathname.endsWith('/extract'))evidence.extractions.push(url.pathname);
});
const api=async route=>{const response=await fetch(session.api+route);assert(response.ok,await response.clone().text());return response.json();};
const button=name=>page.getByRole('button',{name,exact:typeof name==='string'});
const dialog=()=>page.getByRole('dialog');
const urlInput=()=>dialog().locator('input[type=url]');
const rawNav=()=>page.locator('.nav-item').filter({hasText:'Raw 原始资料'}).click();
const open=()=>button(/导入资料/).first().click();
const shot=async name=>{const target=path.join(out,'builder-'+name+'.png');await page.screenshot({path:target,fullPage:true});evidence.screenshots.push(target);};
const expectPost=pathname=>page.waitForResponse(response=>response.request().method()==='POST'&&new URL(response.url()).pathname===pathname);
const posted=async (promise,status)=>{const response=await promise;const data=await response.json();assert.equal(response.status(),status,JSON.stringify(data));return data;};
const hash=text=>createHash('sha256').update(text).digest('hex');

try {
  await page.goto(session.url,{waitUntil:'domcontentloaded'});
  await page.locator('.home-entry-grid').waitFor();
  await rawNav();
  await open();
  await dialog().getByRole('tab',{name:/上传文件/}).click();
  await urlInput().fill(session.fixtures.entry);
  assert.equal(await button('保存并生成 Wiki 草稿').count(),0);
  assert.equal(await dialog().locator('input[data-autofocus]').inputValue(),'');
  assert.equal(await dialog().locator('input[type=file]').inputValue(),'');
  await shot('url-only-form');
  const fetching=expectPost('/api/raw/import');
  await button('从网页导入 Raw').click();
  await button('正在读取网页…').waitFor();
  assert(await button('正在读取网页…').isDisabled());
  await shot('url-reading');
  const fetched=await posted(fetching,201);
  assert.equal(fetched.kind,'url');
  assert.equal(fetched.raw.title,'虚构渠道公开报告');
  assert.equal(fetched.raw.sourceName,new URL(session.fixtures.final).hostname);
  assert.equal(fetched.raw.url,session.fixtures.entry);
  assert.equal(fetched.raw.urlImport.finalUrl,session.fixtures.final);
  assert(Number.isFinite(Date.parse(fetched.raw.urlImport.fetchedAt)));
  assert.equal(fetched.raw.assetId,undefined);
  assert.equal(fetched.asset,undefined);
  const expected='公开报告正文\n\n虚构渠道本年新增签约门店56家。\n\n统计口径只包含当年新签约门店。';
  const persisted=await api('/api/raw/'+fetched.raw.id);
  assert.equal(persisted.body,expected);
  assert.equal(persisted.bodySha256,hash(expected));
  await page.getByRole('heading',{name:'虚构渠道公开报告',exact:true}).waitFor();
  assert.equal(await page.locator('.raw-body').innerText(),expected);
  await page.getByRole('region',{name:'网页导入来源'}).waitFor();
  assert.equal(await page.getByRole('link',{name:session.fixtures.entry,exact:true}).count(),1);
  assert.equal(await page.getByRole('link',{name:session.fixtures.final,exact:true}).count(),1);
  await shot('url-saved-source');
  assert.deepEqual((await api('/__control/counters')).network,['/entry','/article']);
  evidence.checks.push('仅链接空标题/来源/文件经真实HTTP重定向+静态HTML解析，正文、原/最终链接、时间、SHA持久读回，未创建原件');

  await open();
  await urlInput().fill(session.fixtures.script);
  const failure=expectPost('/api/raw/import');
  await button('从网页导入 Raw').click();
  const refused=await posted(failure,422);
  assert.equal(refused.error.code,'URL_BODY_UNAVAILABLE');
  await dialog().getByRole('alert').filter({hasText:'没有取得可保存的静态正文'}).waitFor();
  assert.equal(await urlInput().inputValue(),session.fixtures.script);
  assert.equal((await api('/api/raw')).items.length,1);
  await shot('url-failure-keeps-input');
  const pasted='  用户粘贴的原文\n\n不裁剪首尾。  ';
  await dialog().locator('input[data-autofocus]').fill('保留粘贴正文');
  await dialog().locator('input[placeholder*="客户访谈"]').fill('合成粘贴样例');
  await dialog().locator('textarea').fill(pasted);
  assert.equal(await button('从网页导入 Raw').count(),0);
  const pasteRequest=expectPost('/api/raw');
  await button('仅保存 Raw').click();
  const savedPaste=await posted(pasteRequest,201);
  assert.equal(savedPaste.body,pasted);
  assert.equal(savedPaste.bodySha256,hash(pasted));
  assert.equal(savedPaste.url,session.fixtures.script);
  assert.equal(savedPaste.urlImport,undefined);
  await page.getByRole('heading',{name:'保留粘贴正文',exact:true}).waitFor();
  assert.deepEqual((await api('/__control/counters')).network,['/entry','/article','/script-only']);
  await shot('paste-no-fetch');
  evidence.checks.push('JS-only页面422无新增Raw，保留链接可粘贴补救，首尾空白和换行原样保存且没有第二次读取');

  await open();
  await urlInput().fill(session.fixtures.bad);
  await dialog().locator('textarea').fill('优先级断言：粘贴文本不应进入文件正文。');
  await dialog().getByRole('tab',{name:/上传文件/}).click();
  const fileBody='  原件静态内容\n\n这是文件正文。  ';
  await dialog().locator('input[type=file]').setInputFiles({name:'虚构文件来源.txt',mimeType:'text/plain',buffer:Buffer.from(fileBody)});
  await dialog().getByRole('tab',{name:/粘贴文本/}).click();
  assert.match(await dialog().locator('.file-picked').innerText(),/本次使用文件\s+虚构文件来源\.txt/);
  await button('移除文件').waitFor();
  await shot('file-priority-across-tabs');
  const fileRequest=expectPost('/api/raw/import');
  await button('仅保存 Raw').click();
  const savedFile=await posted(fileRequest,201);
  assert.equal(savedFile.kind,'file');
  assert.equal(savedFile.raw.body,fileBody);
  assert.equal(savedFile.raw.bodySha256,hash(fileBody));
  assert.equal(savedFile.asset.sha256,hash(fileBody));
  assert.equal(savedFile.raw.url,session.fixtures.bad);
  assert.equal(savedFile.raw.urlImport,undefined);
  assert.deepEqual((await api('/__control/counters')).network,['/entry','/article','/script-only']);
  await button('查看这条资料').click();
  await page.getByRole('heading',{name:'虚构文件来源',exact:true}).waitFor();
  await shot('file-retained-source');
  evidence.checks.push('文件、正文与坏URL同时存在时，跨标签显示文件优先，只请求文件导入，原件SHA与Raw正文保持，URL没有网络请求');

  await open();
  await urlInput().fill(session.fixtures.bad);
  await dialog().getByRole('tab',{name:/上传文件/}).click();
  await dialog().locator('input[type=file]').setInputFiles({name:'不可解析.txt',mimeType:'text/plain',buffer:Buffer.from([0x61,0xff,0xfe,0x80])});
  const badFile=expectPost('/api/raw/import');
  await button('仅保存 Raw').click();
  const parseFailure=await posted(badFile,415);
  assert.equal(parseFailure.error.code,'UNSUPPORTED_ENCODING');
  assert.equal(parseFailure.error.details.retained,true);
  await dialog().getByRole('alert').filter({hasText:'原件已保留'}).waitFor();
  assert.equal((await api('/api/raw')).items.length,3);
  assert.deepEqual((await api('/__control/counters')).network,['/entry','/article','/script-only']);
  await shot('file-parse-failure-no-url-fallback');
  await button('移除文件').click();
  await button('从网页导入 Raw').waitFor();
  await button('取消').click();
  await open();
  await button('仅保存 Raw').click();
  await dialog().getByRole('alert').filter({hasText:'请上传文件、粘贴正文或填写一个可读取的公开网页链接'}).waitFor();
  assert.equal((await api('/api/raw')).items.length,3);
  await button('取消').click();
  const counters=await api('/__control/counters');
  assert.equal(counters.provider,0);
  assert.equal(counters.realProviderCalls,0);
  assert.deepEqual(evidence.extractions,[]);
  assert.deepEqual(evidence.externalBrowserRequests,[]);
  assert.deepEqual(evidence.pageErrors,[]);
  evidence.checks.push('解析失败只保留原件，无新增Raw、无URL回退；移除文件后才重新显示显式网页动作，三者空具体报错。全部浏览器动作未请求LLM');
  evidence.counters=counters;
  evidence.success=true;
} catch(error) {
  evidence.failure={message:error.message,stack:error.stack};
  await shot('failure');
  throw error;
} finally {
  await writeFile(path.join(out,'builder-browser.json'),JSON.stringify(evidence,null,2));
  await browser.close();
}

