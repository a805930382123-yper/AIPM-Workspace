import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const session = JSON.parse(await readFile(process.argv[2], 'utf8'));
const out = path.resolve('docs/reports/RAWUX01-20261106-evidence');
await mkdir(out,{recursive:true});
const {chromium} = createRequire(import.meta.url)(path.join(os.homedir(), '.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const browser = await chromium.launch({executablePath:path.join(os.homedir(),'AppData/Local/Google/Chrome/Application/chrome.exe'), args:['--no-proxy-server'], headless:true});
const page = await browser.newPage({viewport:{width:1536,height:1050}});
page.setDefaultTimeout(15000);
const evidence = {success:false, screenshots:[], checks:[], pageErrors:[], approvals:[]};
page.on('pageerror', e => evidence.pageErrors.push(e.message));
page.on('request', r => { if (r.method() !== 'GET' && /\/review\/(pages|start|structured-note)/.test(r.url())) evidence.approvals.push(r.url()); });
const button = name => page.getByRole('button',{name, exact:typeof name==='string'});
const api = async (route, body) => {
  const r = await fetch(session.api+route,body===undefined?{}:{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});
  assert(r.ok,await r.clone().text());
  return r.json();
};
const shot = async (name, fullPage = true) => {
  const target = path.join(out,`review-${name}.png`);
  await page.screenshot({path:target,fullPage});
  evidence.screenshots.push(target);
};
const action = async (method, suffix, click, code) => {
  const next = page.waitForResponse(r => r.request().method()===method && new URL(r.url()).pathname.endsWith(suffix));
  await click();
  const response = await next;
  assert.equal(response.status(),code,await response.text());
  return {payload:response.request().postDataJSON(), response:await response.json()};
};
const raw = () => page.locator('.nav-item').filter({hasText:'Raw 原始资料'}).click();
const openOld = async title => {
  await raw();
  await page.locator('.raw-list-item').filter({hasText:title}).click();
  await button('继续审核').click();
  await page.getByRole('heading',{name:'整理成果',exact:true}).waitFor();
};
const digestFile = async draftId => createHash('sha256').update(await readFile(path.join(session.root,'drafts',draftId+'.json'))).digest('hex');
const done = () => page.getByRole('region',{name:'已入库成果',exact:true}).waitFor();
const confirm = () => button(/确认所选成果入库（\d+）/);
const select = title => page.getByRole('checkbox',{name:`选择入库 ${title}`,exact:true});
const confirmScope = () => page.getByRole('region',{name:'整体确认入库',exact:true});

try {
  await page.goto(session.url,{waitUntil:'domcontentloaded'});
  await page.locator('.home-entry-grid').waitFor();
  const ids = session.fixtures;
  const stdBefore = await digestFile(ids.oldStandard);
  await openOld('旧标准草稿');
  assert.equal(await digestFile(ids.oldStandard),stdBefore);
  const standardCard = page.getByRole('article',{name:'成果 旧配送约定',exact:true});
  await standardCard.locator('summary').filter({hasText:'阅读完整主题成果'}).click();
  await standardCard.locator('summary').filter({hasText:'原文引用与位置'}).click();
  const quote = await standardCard.locator('blockquote').first().innerText();
  await standardCard.getByRole('button',{name:/打开原句/}).first().click();
  const mark = page.locator('.raw-body mark[data-citation-start]');
  assert.equal(await mark.innerText(),quote);
  await shot('legacy-exact-evidence',false);
  await button('继续审核').click();
  await page.getByRole('heading',{name:'整理成果',exact:true}).waitFor();
  await select('旧退货口径').uncheck();
  const oldStandard = await action('POST','/confirm',()=>confirm().click(),201);
  await done();
  assert.equal(oldStandard.payload.selectedPageIds.length,1);
  assert.match(oldStandard.payload.outcomeDigest,/^[a-f0-9]{64}$/);
  const standardWiki = await api('/api/wiki/'+oldStandard.response.wikiIds[0]);
  assert.equal(standardWiki.title,'旧配送约定');
  assert.equal((await api('/api/wiki')).items.some(p=>p.title==='旧退货口径'),false);
  await shot('legacy-standard-result');

  const deepBefore = await digestFile(ids.oldDeep);
  const deepRaw = await api('/api/raw/'+ids.deep);
  const deepView = await api('/api/drafts/'+ids.oldDeep);
  assert.equal(deepView.humanReview.units.length,32);
  assert.equal(deepView.pages.filter(p=>p.selected).length,10);
  assert.equal(deepView.humanReview.approvals.length,2);
  assert.equal(deepView.noteApproval,undefined);
  await openOld('旧深度草稿');
  assert.equal(await digestFile(ids.oldDeep),deepBefore);
  assert.equal(await page.locator('.note-approval').count(),0);
  assert.equal(await confirm().isEnabled(),true);
  await shot('legacy-deep-ready-without-approvals');
  await page.locator('.outcome-card').last().scrollIntoViewIfNeeded();
  const pinned = await confirm().boundingBox();
  assert(pinned && pinned.y >= 0 && pinned.y + pinned.height <= 1050);
  await shot('legacy-deep-sticky-confirm',false);
  for(let i=2;i<=10;i++) await select(`旧渠道样点 ${i}`).uncheck();
  const deepResult = await action('POST','/confirm',()=>confirm().click(),201);
  await done();
  assert.equal(deepResult.response.wikiIds.length,1);
  assert.equal((await api('/api/raw/'+ids.deep)).bodySha256,deepRaw.bodySha256);
  const formalDeep = await api('/api/wiki/'+deepResult.response.sourceId);
  assert(formalDeep.body.includes('深度整理笔记'));

  await openOld('仅来源笔记');
  assert.match(await confirmScope().innerText(),/本次主题 0 项/);
  await shot('source-only-confirm');
  const only = await action('POST','/confirm',()=>button('仅确认来源笔记入库').click(),201);
  await done();
  assert.deepEqual(only.response.wikiIds,[]);
  assert.equal((await api('/api/wiki/'+only.response.sourceId)).type,'source');
  evidence.checks.push('旧标准展开主题引用后精确定位 Raw 原句；32 单元 10 已选 2 旧审批的旧深度仍可整体确认，十主题滚动时确认按钮留在视窗；旧标准和旧深度只写选择项，Source-only 单独写入');

  await raw();
  await button(/导入资料/).first().click();
  await page.getByPlaceholder('例如：经销商订货流程访谈纪要').fill('RAWUX01 新导入渠道报告');
  await page.getByPlaceholder('例如：客户访谈 / 公众号名称').fill('虚构渠道调查');
  await page.locator('.body-field textarea').fill('虚构新渠道覆盖85家。\n\n虚构区域签约门店56家，口径为当年新签。');
  await shot('raw-import');
  const savedRaw = await action('POST','/api/raw',()=>button('仅保存 Raw').click(),201);
  await page.getByRole('heading',{name:'RAWUX01 新导入渠道报告',exact:true}).waitFor();
  await page.getByLabel('整理模式',{exact:true}).selectOption('standard');
  await api('/__control/delay',{ms:550});
  await api('/__control/fail-provider',{stage:'maintenance'});
  await action('POST','/extract',()=>button('整理并融入知识库').click(),202);
  await shot('raw-generation-progress');
  await button('显式继续提取').waitFor();
  await shot('raw-generation-failed');
  await action('POST','/extract',()=>button('显式继续提取').click(),202);
  await page.getByRole('heading',{name:'整理成果',exact:true}).waitFor();
  const card = page.getByRole('article',{name:'成果 新渠道覆盖',exact:true});
  assert.match(await card.locator('.outcome-excerpt').innerText(),/虚构/);
  await shot('new-outcome-preview');
  await select('新渠道覆盖').check();
  await card.locator('summary').filter({hasText:'阅读完整主题成果'}).click();
  await card.getByRole('button',{name:'编辑主题成果',exact:true}).click();
  const text = card.locator('.outcome-edit textarea');
  await text.fill((await text.inputValue())+'\n\n人工核实补充：覆盖仅供渠道样例。');
  assert.equal(await confirm().isDisabled(),true);
  await api('/__control/fail-save',{});
  await action('POST','/changes/review',()=>card.getByRole('button',{name:'保存成果编辑',exact:true}).click(),503);
  await page.getByRole('alert').filter({hasText:'本次草稿写入失败'}).waitFor();
  assert.match(await text.inputValue(),/人工核实补充/);
  assert.equal(await confirm().isDisabled(),true);
  await shot('new-edit-save-failed');
  await action('POST','/changes/review',()=>card.getByRole('button',{name:'保存成果编辑',exact:true}).click(),200);
  await card.getByRole('button',{name:'编辑主题成果',exact:true}).waitFor();
  await shot('new-edited-selection');
  const beforeFormal = (await api('/api/wiki')).items.length;
  await api('/__control/fail-commit',{});
  const fault = await action('POST','/confirm',()=>confirm().click(),500);
  assert.equal(fault.payload.selectedPageIds.length,1);
  await page.getByRole('region',{name:'提交恢复',exact:true}).waitFor();
  await shot('new-recoverable-write');
  const retry = await action('POST','/confirm',()=>button('继续上次确认').click(),201);
  await done();
  assert.equal(retry.payload.idempotencyKey,fault.payload.idempotencyKey);
  assert.equal(retry.response.wikiIds.length,1);
  const formal = await api('/api/wiki/'+retry.response.wikiIds[0]);
  assert.match(formal.body,/人工核实补充/);
  assert.equal((await api('/api/wiki')).items.length,beforeFormal+2);
  assert.equal((await api('/api/raw/'+savedRaw.response.id)).bodySha256,savedRaw.response.bodySha256);
  await button('打开正式主题').click();
  await page.getByRole('heading',{name:formal.title,exact:true}).waitFor();
  await shot('new-formal-readback');
  assert.deepEqual(evidence.approvals,[]);
  assert.deepEqual(evidence.pageErrors,[]);
  evidence.checks.push('真实粘贴导入、阶段和失败继续、新维护成果编辑、部分写失败同key恢复、正式Wiki阅读；原Raw SHA保持');
  evidence.success=true;
} catch(error) {
  evidence.error={message:error.message,stack:error.stack};
  await shot('failure');
  throw error;
} finally {
  await writeFile(path.join(out,'review-browser.json'),JSON.stringify(evidence,null,2));
  await browser.close();
}
