import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir, readFile, readdir, writeFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import os from 'node:os';
import path from 'node:path';

const session=JSON.parse(await readFile(process.argv[2],'utf8'));
const out=path.resolve(process.argv[3]??'docs/reports/PDF01-R2-20261110-ui-evidence');
const compactOnly=process.argv[4]==='compact';
await mkdir(out,{recursive:true});
const {chromium}=createRequire(import.meta.url)(path.join(os.homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const browser=await chromium.launch({executablePath:path.join(os.homedir(),'AppData/Local/Google/Chrome/Application/chrome.exe'),args:['--no-proxy-server'],headless:true});
const page=await browser.newPage({viewport:{width:1536,height:1050}});
page.setDefaultTimeout(16000);
const evidence={success:false,screenshots:[],pageErrors:[],outside:[],checks:[]};
page.on('pageerror',error=>evidence.pageErrors.push(error.message));
page.on('request',request=>{
  const url=new URL(request.url());
  if(['http:','https:'].includes(url.protocol)&&url.origin!==session.url)evidence.outside.push(url.origin);
});
const digest=bytes=>createHash('sha256').update(bytes).digest('hex');
const api=async(route,method='GET',body)=>{
  const response=await fetch(session.url+route,{method,headers:body?{'content-type':'application/json'}:undefined,body:body?JSON.stringify(body):undefined});
  assert(response.ok,`${method} ${route} ${response.status} ${await response.clone().text()}`);
  return response.json();
};
const original=async route=>Buffer.from(await (await fetch(session.url+route)).arrayBuffer());
const calls=async()=>(await api('/__control/counters')).calls;
const button=name=>page.getByRole('button',{name,exact:typeof name==='string'});
const cleanup=()=>page.getByRole('region',{name:'PDF 内容清理与知识草稿'});
const heading=name=>page.getByRole('heading',{name,exact:true});
const rawNav=()=>page.locator('.nav-item').filter({hasText:'Raw 原始资料'}).click();
const responseTo=(route,method='POST')=>page.waitForResponse(response=>response.request().method()===method&&new URL(response.url()).pathname===route);
const post=async(route,label,expected)=>{
  const pending=responseTo(route);
  await button(label).click();
  const response=await pending;
  const body=await response.json();
  assert(expected.includes(response.status()),`${route} ${response.status()} ${JSON.stringify(body)}`);
  return body;
};
const shot=async(name,locator)=>{
  if(compactOnly&&name!=='07a-compact-outcome')return;
  if(locator)await locator.scrollIntoViewIfNeeded();
  const target=path.join(out,`builder-${name}.png`);
  await page.screenshot({path:target});
  evidence.screenshots.push(target);
};
const wikiSnapshot=async()=>{
  const dir=path.join(session.root,'knowledge','wiki');
  const files=(await readdir(dir)).filter(file=>file.endsWith('.md')).sort();
  return Object.fromEntries(await Promise.all(files.map(async file=>[file,digest(await readFile(path.join(dir,file)))])));
};
const openDraft=async()=>{await button('打开知识草稿').click();await heading('整理成果').waitFor();};

async function drive(){
  const schema=await api('/api/wiki/schema');
  const wikiInput={title:'区域样本',type:'concept',category:schema.categories[0].id,body:'## 人工保留\n\n这段人工记录应当保留。'};
  const existing=await api('/api/wiki','POST',wikiInput);
  const before=await wikiSnapshot();
  await page.goto(session.url,{waitUntil:'domcontentloaded'});
  await rawNav();
  await button(/导入资料/).first().click();
  const dialog=page.getByRole('dialog');
  await dialog.getByRole('tab',{name:/上传文件/}).click();
  await dialog.locator('input[type=file]').setInputFiles(session.fixtures.mixed);
  const {raw}=await post('/api/raw/import','仅保存 Raw',[201]);
  await button('查看这条资料').click();
  const rawBase=`/api/raw/${raw.id}`,pdfBase=`${rawBase}/pdf`,cleanupPath=`${pdfBase}/cleanup`;
  const sourceFile=await readFile(session.fixtures.mixed);
  assert.equal(raw.assetSha256,digest(sourceFile));
  assert.deepEqual(await original(`${pdfBase}/original`),sourceFile);
  assert.deepEqual(await calls(),[]);
  await post(`${pdfBase}/understand`,'开始 AI 页理解',[202]);
  await page.getByRole('status').filter({hasText:'页理解未完成 · 3/4 页'}).waitFor();
  await page.getByRole('link',{name:'内容清理与知识草稿',exact:true}).click();
  await cleanup().getByText(/仍有 1 页未完成 AI 页理解：第 4 页/).waitFor();
  assert(await button('开始内容清理').isDisabled());
  await shot('01-missing-scope',cleanup());
  await cleanup().getByLabel('清理范围').selectOption('range');
  await cleanup().getByLabel('结束页').fill('3');
  await shot('02-explicit-page-range',cleanup());
  await post(cleanupPath,'开始内容清理',[202]);
  await cleanup().getByRole('status').filter({hasText:'未完成 · 归并主题'}).waitFor();
  await shot('03-index-failed',cleanup());
  const failedCalls=await calls();
  assert.equal(failedCalls.filter(call=>call.stage==='pdf_cleanup').length,1);
  await page.reload({waitUntil:'domcontentloaded'});
  await rawNav();
  await cleanup().getByRole('status').filter({hasText:'未完成 · 归并主题'}).waitFor();
  assert.deepEqual(await calls(),failedCalls);
  await post(cleanupPath,'继续内容清理',[202]);
  await cleanup().getByRole('status').filter({hasText:'已完成 · 清理与归并完成'}).waitFor();
  const doneCalls=await calls();
  assert.equal(doneCalls.filter(call=>call.stage==='pdf_cleanup').length,1);
  assert.equal(doneCalls.filter(call=>call.stage==='pdf_topic_index').length,2);
  assert.match(await cleanup().innerText(),/第 1–3 页 · 共 4 页/);
  await shot('04-cleanup-summary',cleanup());
  await cleanup().getByText(/查看保留、归并与略过理由/).click();
  await cleanup().getByText('装饰与主办方宣传，无研究依据',{exact:true}).first().waitFor();
  await shot('05-skipped-reasons',cleanup().getByText('装饰与主办方宣传，无研究依据',{exact:true}).first());
  await cleanup().getByRole('button',{name:'查看第 3 页证据',exact:true}).first().click();
  const image=page.getByRole('img',{name:'PDF 第 3 页',exact:true});
  await image.evaluate(element=>element.decode());
  await shot('06-source-page',image);
  const generated=await post(`${cleanupPath}/draft`,'生成知识草稿',[200]);
  const draftId=generated.job.draftId;
  const draftPath=`/api/drafts/${draftId}`;
  assert.deepEqual(await calls(),doneCalls);
  await openDraft();
  const initial=await api(draftPath);
  assert.equal(initial.pdfInput.startPage,1);
  assert.equal(initial.pdfInput.endPage,3);
  assert(initial.maintenance.changes.some(change=>change.targetWikiId===existing.id));
  assert.match(initial.outcomeDigest,/^[a-f0-9]{64}$/);
  const compactSummaries=await page.locator('.outcome-excerpt').allTextContents();
  assert.equal(compactSummaries.length,2);
  assert(compactSummaries.every(summary=>summary.trim()&&!summary.includes('/api/raw/')&&!summary.includes('|')));
  await shot('07a-compact-outcome',page.getByRole('region',{name:'整体确认入库'}));
  if(compactOnly){
    assert.deepEqual(await wikiSnapshot(),before);
    assert.deepEqual(evidence.pageErrors,[]);
    assert.deepEqual(evidence.outside,[]);
    evidence.checks.push('两条 PDF 候选的紧凑摘要均显示可读证据，去除了 API 链接串和表格分隔符。');
    evidence.success=true;
    return;
  }
  const region=page.getByRole('article',{name:'成果 区域样本'});
  await region.getByText(/阅读完整主题成果/).click();
  await region.getByText(/PDF 原页依据/).click();
  const originalLink=region.getByRole('link',{name:'打开原 PDF 第 3 页',exact:true}).first();
  const popup=page.waitForEvent('popup');
  await originalLink.click();
  const opened=await popup;
  assert.equal(new URL(opened.url()).hash,'#page=3');
  await opened.close();
  await shot('07-outcome-and-page-evidence',originalLink);
  await region.getByRole('button',{name:'编辑主题成果',exact:true}).click();
  const editor=region.getByLabel('成果正文');
  await editor.fill(`${await editor.inputValue()}\n\n## 人工补充\n\n请优先核对有效样本。`);
  await region.getByRole('button',{name:'保存成果编辑',exact:true}).click();
  await page.getByText('草稿已保存，请查看更新后的成果。',{exact:true}).waitFor();
  const edited=await api(draftPath);
  assert.notEqual(edited.outcomeDigest,initial.outcomeDigest);
  assert.match(edited.maintenance.changes.find(change=>change.targetWikiId===existing.id).candidate.body,/请优先核对有效样本/);
  assert.deepEqual(await wikiSnapshot(),before);
  await region.getByRole('checkbox',{name:'选择入库 区域样本'}).check();
  await shot('08-selected-and-edited',page.getByRole('region',{name:'整体确认入库'}));

  const changed=await api(`/api/wiki/${existing.id}`,'PUT',{...wikiInput,body:`${wikiInput.body}\n\n独立并发修订。`,baseRevision:existing.revision});
  const concurrent=await wikiSnapshot();
  const conflict=await post(`${draftPath}/confirm`,'确认所选成果入库（1）',[409]);
  assert.equal(conflict.error.code,'WIKI_REVISION_CONFLICT');
  await page.getByRole('alert').filter({hasText:'返回 PDF 重新生成草稿并审阅'}).waitFor();
  assert.deepEqual(await wikiSnapshot(),concurrent);
  await shot('09-concurrent-conflict',page.getByRole('alert').filter({hasText:'返回 PDF 重新生成草稿并审阅'}));
  await button('全部不采纳').click();
  await button('确认全部不采纳').click();
  await page.getByText('本次成果全部不采纳，已保留整理历史。',{exact:true}).waitFor();
  await button('查看原始资料').click();
  await button('重新生成知识草稿').waitFor();
  const regenerated=await post(`${cleanupPath}/draft`,'重新生成知识草稿',[200]);
  assert.notEqual(regenerated.job.draftId,draftId);
  assert.deepEqual(await calls(),doneCalls);
  await openDraft();
  const newPath=`/api/drafts/${regenerated.job.draftId}`;
  const fresh=await api(newPath);
  assert.equal(fresh.maintenance.changes.find(change=>change.targetWikiId===existing.id).baseRevision,changed.revision);
  await region.getByText(/阅读完整主题成果/).click();
  await region.getByRole('button',{name:'编辑主题成果',exact:true}).click();
  await editor.fill(`${await editor.inputValue()}\n\n## 人工补充\n\n请优先核对有效样本。`);
  await region.getByRole('button',{name:'保存成果编辑',exact:true}).click();
  await page.getByText('草稿已保存，请查看更新后的成果。',{exact:true}).waitFor();
  await region.getByRole('checkbox',{name:'选择入库 区域样本'}).check();
  assert.deepEqual(await wikiSnapshot(),concurrent);
  const committed=await post(`${newPath}/confirm`,'确认所选成果入库（1）',[200,201]);
  await page.getByRole('region',{name:'已入库成果',exact:true}).waitFor();
  await shot('10-confirmed',page.getByRole('region',{name:'已入库成果',exact:true}));
  const official=await api(`/api/wiki/${existing.id}`);
  assert.match(official.body,/独立并发修订/);
  assert.match(official.body,/请优先核对有效样本/);
  assert.match(official.body,/#page=3/);
  assert.match(official.body,/样本门店分布/);
  assert.match(official.body,/华南.*120/);
  assert.match(official.body,/华东.*200/);
  assert.match(official.body,/表注：仅统计有效样本/);
  assert(official.sources.includes(raw.id));
  assert(committed.sourceId);
  const source=await api(`/api/wiki/${committed.sourceId}`);
  assert.match(source.body,/PDF 整理范围：\[第 1–3 页\]\(.+#page=1\)/);
  await page.getByRole('region',{name:'已入库成果',exact:true}).getByRole('button',{name:'打开正式主题',exact:true}).click();
  const wiki=page.locator('.wiki-detail');
  await wiki.getByRole('heading',{name:'区域样本',exact:true}).waitFor();
  await wiki.getByRole('button',{name:'阅读视图',exact:true}).click();
  const table=wiki.getByRole('table');
  await table.getByRole('columnheader',{name:'样本（家）',exact:true}).waitFor();
  await table.getByRole('row').filter({hasText:'华南'}).getByRole('cell',{name:'120',exact:true}).waitFor();
  await table.getByRole('row').filter({hasText:'华东'}).getByRole('cell',{name:'200',exact:true}).waitFor();
  const formalEvidence=table.getByRole('link',{name:'第 3 页',exact:true}).first();
  await formalEvidence.waitFor();
  assert.equal(await formalEvidence.getAttribute('href'),`${pdfBase}/original#page=3`);
  await shot('11-formal-page-source',formalEvidence);
  await formalEvidence.click();
  await page.waitForURL(`${session.url}${pdfBase}/original#page=3`);
  assert(!(await api('/api/wiki')).items.some(item=>item.title==='研究方法'));
  assert.notDeepEqual(await wikiSnapshot(),concurrent);
  assert.deepEqual(await original(`${pdfBase}/original`),sourceFile);
  assert.equal((await api(rawBase)).bodySha256,raw.bodySha256);
  assert.deepEqual(await calls(),doneCalls);
  assert.deepEqual(evidence.pageErrors,[]);
  assert.deepEqual(evidence.outside,[]);
  evidence.checks.push('缺页阻止整份清理，显式选第 1–3 页；归并失败重载零调用，继续复用清理批次。','归属理由按需展开，扫描和矢量证据可回原页。','编辑改变草稿摘要；正式 Wiki 文件在生成、编辑、选择和冲突后保持原SHA；明确确认后仅写入所选。','409保留原稿，可结束选择并基于新目标版本重新生成；原件与Raw保持原样。');
  evidence.hashes={before,concurrent,after:await wikiSnapshot(),source:raw.assetSha256};
  evidence.calls=doneCalls;
  evidence.success=true;
}
try{await drive();}catch(error){
  evidence.failure=error.stack??String(error);
  await shot('failure').catch(()=>{});
  process.exitCode=1;
}finally{
  await writeFile(path.join(out,'builder-browser-result.json'),JSON.stringify(evidence,null,2));
  console.log(JSON.stringify(evidence,null,2));
  await browser.close();
}
