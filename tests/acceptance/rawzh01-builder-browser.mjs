import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {createRequire} from 'node:module';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';

const session=JSON.parse(await readFile(process.argv[2],'utf8'));
const out=path.resolve(process.argv[3] ?? 'docs/reports/RAWZH01-20261106-evidence');
await mkdir(out,{recursive:true});
const {chromium}=createRequire(import.meta.url)(path.join(os.homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));
const browser=await chromium.launch({executablePath:path.join(os.homedir(),'AppData/Local/Google/Chrome/Application/chrome.exe'),args:['--no-proxy-server'],headless:true});
const page=await browser.newPage({viewport:{width:1536,height:1050}});
page.setDefaultTimeout(20000);
const evidence={success:false,checks:[],screenshots:[],pageErrors:[],outside:[],posts:[]};
page.on('pageerror',e=>evidence.pageErrors.push(e.message));
page.on('request',request=>{
  const url=new URL(request.url());
  if(['http:','https:'].includes(url.protocol)&&url.origin!==session.url)evidence.outside.push(url.origin);
  if(request.method()==='POST')evidence.posts.push(url.pathname);
});
const api=async route=>{const response=await fetch(session.api+route);assert(response.ok,await response.clone().text());return response.json();};
const button=name=>page.getByRole('button',{name,exact:typeof name==='string'});
const dialog=()=>page.getByRole('dialog');
const urlInput=()=>dialog().locator('input[type=url]');
const checkbox=()=>dialog().getByRole('checkbox',{name:'翻译成中文（会调用已配置模型）',exact:true});
const rawNav=()=>page.locator('.nav-item').filter({hasText:'Raw 原始资料'}).click();
const open=()=>button(/导入资料/).first().click();
const shot=async name=>{const target=path.join(out,'builder-'+name+'.png');await page.screenshot({path:target,fullPage:true});evidence.screenshots.push(target);};
const expectPost=pathname=>page.waitForResponse(response=>response.request().method()==='POST'&&new URL(response.url()).pathname===pathname);
const posted=async (promise,status)=>{const response=await promise;const data=await response.json();assert.equal(response.status(),status,JSON.stringify(data));return {data,payload:response.request().postDataJSON()};};
const rawBody=()=>page.locator('.raw-body');
const reading=()=>page.getByRole('group',{name:'正文语言'});
const hash=text=>createHash('sha256').update(text).digest('hex');
const heading=title=>page.getByRole('heading',{name:title,exact:true});
const counters=()=>api('/__control/counters');
const importUrl=async (url,expected,title,defaultShot=false)=>{
  await open();
  await urlInput().fill(url);
  assert.equal(await checkbox().isChecked(),true);
  if(!expected)await checkbox().uncheck();
  if(defaultShot)await shot(expected?'url-default-checked':'url-unchecked');
  const next=expectPost('/api/raw/import');
  await button('从网页导入 Raw').click();
  const {data,payload}=await posted(next,201);
  assert.equal(payload.translateToChinese,expected);
  assert.equal(data.kind,'url');
  await heading(title).waitFor();
  return data;
};

try {
  await page.goto(session.url,{waitUntil:'domcontentloaded'});
  await page.locator('.home-entry-grid').waitFor();
  await rawNav();
  const f=session.fixtures;
  const english=await importUrl(f.english,true,'English Channel Report',true);
  assert(['queued','running'].includes(english.translation.status));
  await page.getByRole('region',{name:'翻译进度'}).waitFor();
  assert.equal(await rawBody().innerText(),f.original);
  await shot('translation-progress');
  await reading().waitFor();
  assert.equal(await rawBody().innerText(),f.translated);
  assert.equal(await reading().getByRole('button',{name:'中文译文',exact:true}).getAttribute('aria-pressed'),'true');
  await shot('chinese-default-reading');
  await reading().getByRole('button',{name:'原文',exact:true}).click();
  assert.equal(await rawBody().innerText(),f.original);
  await shot('english-original-toggle');
  const before=await api('/api/raw/'+english.raw.id);
  assert.equal(before.bodySha256,hash(f.original));
  assert.equal(before.body,f.original);
  assert.equal(before.url,f.english);
  assert.deepEqual((await counters()).translation.map(x=>x.body),[f.original]);
  assert.equal((await counters()).extraction,0);
  assert.equal((await api('/api/raw')).items.length,1);
  const postCount=evidence.posts.length;
  await page.reload({waitUntil:'domcontentloaded'});
  await rawNav();
  await heading('English Channel Report').waitFor();
  await reading().waitFor();
  assert.equal(await rawBody().innerText(),f.translated);
  assert.equal(evidence.posts.length,postCount);
  assert.equal((await counters()).translation.length,1);
  evidence.checks.push('默认勾选经真实URL导入和持久翻译任务，一次假模型调用保存完整段落，自动中文，可切原文，刷新只GET，Raw原文/SHA/来源一致');

  const opt=await importUrl(f.optedOut,false,'English Only Report',true);
  assert.equal(opt.translation,undefined);
  assert.equal((await api('/api/raw/'+opt.raw.id+'/translation')).translation,null);
  assert.equal(await rawBody().innerText(),f.original);
  const cn=await importUrl(f.chinese,true,'中文渠道报告');
  assert.equal(cn.translation.status,'skipped');
  await page.getByText(/正文以中文为主/).waitFor();
  assert.equal(await rawBody().innerText(),f.translated);
  assert.equal((await counters()).translation.length,1);
  await shot('chinese-skip-no-translation');
  evidence.checks.push('取消勾选英文与主要中文页面均原文阅读，额外模型请求0');

  const failed=await importUrl(f.fail,true,'Translation Retry Report');
  await page.getByRole('alert').filter({hasText:'原始资料已保存，中文翻译未完成'}).waitFor();
  assert.equal(await rawBody().innerText(),f.failedOriginal);
  await shot('failed-translation-raw-kept');
  const beforeRetry=await counters();
  const retry=expectPost('/api/raw/'+failed.raw.id+'/translation/retry');
  await button('重试翻译').click();
  const retryResult=await posted(retry,200);
  assert.equal(retryResult.data.translation.rawId,failed.raw.id);
  await reading().waitFor();
  assert.equal(await rawBody().innerText(),f.recovered);
  await shot('retry-same-raw-completed');
  const afterRetry=await counters();
  assert.deepEqual(afterRetry.network,beforeRetry.network);
  assert.equal(afterRetry.translation.length,beforeRetry.translation.length+1);
  assert.equal((await api('/api/raw')).items.length,4);
  assert.equal((await api('/api/raw/'+failed.raw.id)).bodySha256,hash(f.failedOriginal));
  evidence.checks.push('模型失败后原Raw可读且SHA一致，手动重试同ID，不再抓网页或新建Raw');

  const slow=await importUrl(f.slow,true,'Translation Cancellation Report');
  await page.getByRole('region',{name:'翻译进度'}).waitFor();
  const cancel=expectPost('/api/raw/'+slow.raw.id+'/translation/cancel');
  await button('取消翻译').click();
  assert.equal((await posted(cancel,200)).data.translation.status,'cancelled');
  await button('继续翻译').waitFor();
  await shot('cancelled-original-available');

  await open();
  await urlInput().fill(f.unavailable);
  assert.equal(await checkbox().isChecked(),true);
  await dialog().locator('input[data-autofocus]').fill('粘贴英文资料');
  await dialog().locator('input[placeholder*="客户访谈"]').fill('虚构来源');
  await dialog().locator('textarea').fill(f.original);
  assert.equal(await checkbox().count(),0);
  const paste=expectPost('/api/raw');
  await button('仅保存 Raw').click();
  const pasted=await posted(paste,201);
  assert.equal(Object.hasOwn(pasted.payload,'translateToChinese'),false);
  assert.equal(pasted.data.body,f.original);
  await heading('粘贴英文资料').waitFor();

  await open();
  await urlInput().fill(f.unavailable);
  assert.equal(await checkbox().isChecked(),true);
  await dialog().getByRole('tab',{name:/上传文件/}).click();
  await dialog().locator('input[type=file]').setInputFiles({name:'English file.txt',mimeType:'text/plain',buffer:Buffer.from(f.original)});
  assert.equal(await checkbox().count(),0);
  const file=expectPost('/api/raw/import');
  await button('仅保存 Raw').click();
  const uploaded=await posted(file,201);
  assert.equal(uploaded.data.kind,'file');
  assert.equal(uploaded.data.translation,undefined);
  assert.equal(uploaded.data.raw.body,f.original);
  await button('查看这条资料').click();
  await heading('English file').waitFor();
  const afterMaterials=await counters();
  assert.deepEqual(afterMaterials.network,['/english','/opt-out','/chinese','/fail','/slow']);
  assert.equal(afterMaterials.translation.length,4);
  assert.equal(afterMaterials.extraction,0);
  evidence.checks.push('取消翻译保留原文与显式继续入口。文件与粘贴覆盖此前默认框，额外模型及网页请求0');

  await page.locator('.raw-list-item').filter({hasText:'English Channel Report'}).click();
  await reading().waitFor();
  assert.equal(await rawBody().innerText(),f.translated);
  await page.getByLabel('整理模式',{exact:true}).selectOption('standard');
  await button('整理并融入知识库').click();
  await heading('整理成果').waitFor();
  const outcome=page.locator('.outcome-card').first();
  await outcome.locator('summary').filter({hasText:'阅读完整主题成果'}).click();
  await outcome.locator('summary').filter({hasText:'原文引用与位置'}).click();
  const quote=await outcome.locator('blockquote').first().innerText();
  await outcome.getByRole('button',{name:/打开原句/}).first().click();
  const marker=rawBody().locator('mark[data-citation-start]');
  assert.equal(await marker.innerText(),quote);
  assert.equal(await rawBody().innerText(),f.original);
  assert.equal(await reading().getByRole('button',{name:'原文',exact:true}).getAttribute('aria-pressed'),'true');
  await shot('evidence-forces-english-offset');
  assert.deepEqual(await api('/api/raw/'+english.raw.id),before);
  evidence.checks.push('明确整理使用原文，真实维护成果证据点击强制切换英文并精确定位原句，原Raw与翻译前一致');
  evidence.counters=await counters();
  assert.equal(evidence.counters.realProviderCalls,0);
  assert.deepEqual(evidence.outside,[]);
  assert.deepEqual(evidence.pageErrors,[]);
  evidence.success=true;
} catch(error) {
  evidence.failure={message:error.message,stack:error.stack};
  await shot('failure');
  throw error;
} finally {
  await writeFile(path.join(out,'builder-browser.json'),JSON.stringify(evidence,null,2));
  await browser.close();
}
