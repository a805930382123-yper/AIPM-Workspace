import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {randomUUID} from 'node:crypto';
import {RawStore} from '../../services/raw/store.ts';
import {WikiStore} from '../../services/wiki/store.ts';
import {PromptStore} from '../../services/prompt/store.ts';
import {PromptAiService} from '../../services/prompt-ai/service.ts';
import {BRIEF_CONTRACT,OPTIMIZATION_CONTRACT,contentContract} from '../../services/prompt-ai/contract.ts';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'pa01-astra-spec-'));
const raw=new RawStore(root);await raw.initialize();
const wiki=new WikiStore(root,raw);await wiki.initialize();
const prompts=new PromptStore(root,wiki);await prompts.initialize();
let calls=0,response=OPTIMIZATION_CONTRACT.example;
const provider={name:'spec-local-memory',model:'fixture',cacheIdentity:'spec-fixed',secrets:[],async complete(){calls++;return {text:JSON.stringify(response),finishReason:'stop',bytes:512};}};
const ai=new PromptAiService(root,wiki,prompts,()=>provider);await ai.initialize();
const file=id=>path.join(root,'drafts','prompts',id+'.json');
const capture=async fn=>{try{return {ok:true,value:await fn()};}catch(e){return {ok:false,code:e.code,status:e.status,details:e.details};}};
const rows=[];
response=OPTIMIZATION_CONTRACT.example;
const checked=await ai.check('虚构原 Prompt，请分析访谈资料。','');
const before=await ai.get(checked.draftId);
const categories=(await prompts.schema()).categories.map(x=>x.id);
response=contentContract(categories).example;
const ready=await ai.rewrite(checked.draftId,randomUUID());
const legacyId=randomUUID();
await fs.writeFile(file(legacyId),JSON.stringify({id:legacyId,kind:'optimizer',createdAt:new Date().toISOString(),status:'pending',originalBody:before.originalBody,checks:before.checks,improvements:before.improvements,preview:ready.preview}));
const oldRead=await capture(()=>ai.get(legacyId));
const oldConfirm=await capture(()=>ai.confirm(legacyId,legacyId,'new',ready.preview));
const oldAfter=await capture(()=>ai.get(legacyId));
const oldReplay=await capture(()=>ai.confirm(legacyId,legacyId,'new',ready.preview));
const stored=JSON.parse(await fs.readFile(file(legacyId),'utf8'));
rows.push({id:'S01-legacy-confirm-read-replay',result:oldRead.ok&&oldConfirm.ok&&oldAfter.ok&&oldReplay.ok?'PASS':'FAIL',evidence:{beforeReadable:oldRead.ok,confirmed:oldConfirm.ok,after:oldAfter,replay:oldReplay,persistedSchemaVersion:stored.schemaVersion,persistedStage:stored.stage??null,formalPromptId:oldConfirm.value?.prompt.id}});
response=OPTIMIZATION_CONTRACT.example;
const c2=await ai.check('另一条虚构 Prompt','');
response=contentContract(categories).example;
const n=calls;
const invalid='-'.repeat(36);
const invalidRewrite=await capture(()=>ai.rewrite(c2.draftId,invalid));
const invalidRead=await capture(()=>ai.get(c2.draftId));
rows.push({id:'S02-malformed-request-id',result:!invalidRewrite.ok&&invalidRewrite.status===400&&calls===n&&invalidRead.ok?'PASS':'FAIL',evidence:{requestId:invalid,rewriteAccepted:invalidRewrite.ok,read:invalidRead,extraFakeCalls:calls-n}});
const c3=await (async()=>{response=OPTIMIZATION_CONTRACT.example;return ai.check('第三条虚构 Prompt','');})();
const conflict=await capture(()=>ai.check('目标冲突','',randomUUID(),1));
rows.push({id:'S03-missing-target-diagnostic',result:conflict.details?.category==='conflict'&&conflict.details?.stage==='check'?'PASS':'FAIL',evidence:conflict});
response=BRIEF_CONTRACT.example;
const brief=await ai.brief('控制任务','custom');
rows.push({id:'S04-valid-draft-control',result:(await ai.get(brief.draftId))&&(await ai.get(c3.draftId))?'PASS':'FAIL'});
const report={at:new Date().toISOString(),root,externalCalls:0,fakeCalls:calls,rows,summary:{pass:rows.filter(x=>x.result==='PASS').length,fail:rows.filter(x=>x.result==='FAIL').length}};
await fs.writeFile('docs/reports/PA01-ASTRA-20261015-spec-probes.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
